#!/usr/bin/env python3
"""Regenerate reports/hsp-backlog-obsolescence/REVIEW.md from ledger.jsonl and tickets/*.md.

Machine verdicts are ledger lines with "label". Human verdicts ("human_verdict") override the label.
Verifier lines ("verified_by") are shown as a check mark. The last line per key and kind wins.
"""
import json, re, pathlib
D = pathlib.Path(__file__).resolve().parent.parent / 'reports' / 'hsp-backlog-obsolescence'
LABEL = {'obsolete': 'backlog-review-obsolete', 'unclear': 'backlog-review-unclear',
         'not-implemented': 'backlog-review-not-implemented', 'pending-adam': 'backlog-review-unclear'}
machine, human, verified = {}, {}, {}
for line in (D / 'ledger.jsonl').read_text().splitlines():
    if not line.strip():
        continue
    e = json.loads(line)
    if 'human_verdict' in e: human[e['key']] = e
    elif 'verified_by' in e: verified[e['key']] = e
    elif 'label' in e: machine[e['key']] = e

def summary_and_note(key):
    p = D / 'tickets' / f'{key}.md'
    if not p.exists():
        return '', ''
    t = p.read_text()
    m = re.match(r'#\s*' + re.escape(key) + r':\s*(.+)', t)
    note = t.split('## Note for review', 1)[1].strip() if '## Note for review' in t else ''
    note = re.split(r'(?<=[.?!])\s', note.replace('\n', ' '), maxsplit=1)[0]
    return (m.group(1).strip() if m else ''), note[:200]

groups = {k: [] for k in ['backlog-review-obsolete', 'backlog-review-unclear', 'backlog-review-not-implemented']}
for key, e in machine.items():
    h = human.get(key)
    label = LABEL.get(h['human_verdict'], e['label']) if h else e['label']
    verdict = e['verdict']
    if h:
        verdict += f" → Gabor: {h['human_verdict']}" + (f" ({h['note']})" if h.get('note') else '')
    if key in verified:
        verdict += ' ✓ verified'
    s, note = summary_and_note(key)
    groups[label].append((int(key.split('-')[1]), f'| [{key}](tickets/{key}.md) | {s} | {verdict} | {note} |'))

titles = {'backlog-review-obsolete': 'backlog-review-obsolete (proposed for closing)',
          'backlog-review-unclear': 'backlog-review-unclear (needs a product call)',
          'backlog-review-not-implemented': 'backlog-review-not-implemented'}
out = ['# HSP backlog review', '',
       f'{len(machine)} tickets checked against code on master. The labels are on the tickets in Jira, and the reasoning is in `tickets/`.',
       'Only positive evidence on master earns `backlog-review-obsolete`. `not-implemented` means nothing was found, not that the ticket is still wanted.',
       'Generated by `scripts/hsp-review-gen.py`. Do not edit by hand.', '',
       'Jira filter: `labels in (backlog-review-obsolete, backlog-review-not-implemented, backlog-review-unclear)`']
for label, rows in groups.items():
    out += ['', f'## {titles[label]} ({len(rows)})', '', '| Ticket | Summary | Verdict | Note |', '|---|---|---|---|']
    out += [r for _, r in sorted(rows)] or ['| | none yet | | |']
(D / 'REVIEW.md').write_text('\n'.join(out) + '\n')
print({k: len(v) for k, v in groups.items()}, 'total', len(machine))
